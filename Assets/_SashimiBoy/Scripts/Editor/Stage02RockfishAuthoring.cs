        private static void CaptureCamera(Camera camera,string path)
        {
            var target=new RenderTexture(1200,800,24);var before=RenderTexture.active;
            camera.targetTexture=target;camera.Render();RenderTexture.active=target;
            var texture=new Texture2D(1200,800,TextureFormat.RGB24,false);
            texture.ReadPixels(new Rect(0,0,1200,800),0,0);texture.Apply();
            File.WriteAllBytes(path,texture.EncodeToPNG());camera.targetTexture=null;RenderTexture.active=before;
            Object.DestroyImmediate(texture);Object.DestroyImmediate(target);
        }
