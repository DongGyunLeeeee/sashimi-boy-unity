        public static void AuditModelReapplyBatch()
        {
            string Hash(string path) { using(var sha=System.Security.Cryptography.SHA256.Create())return Convert.ToBase64String(sha.ComputeHash(File.ReadAllBytes(path))); }
            var before=Directory.GetFiles(Root,"*",SearchOption.AllDirectories).ToDictionary(p=>p,p=>Hash(p));
            BuildModels(12);
            var changed=before.Keys.Where(p=>!File.Exists(p)||Hash(p)!=before[p]).ToArray();
            if(changed.Length>0 || Directory.GetFiles(Root,"*",SearchOption.AllDirectories).Length!=before.Count)
                throw new InvalidOperationException("Stage02 model reapply changed generated bytes: "+string.Join(", ",changed));
            Debug.Log("[Stage02] Model reapply byte stability: "+before.Count+" files unchanged.");
        }

